/**
 * healthReport.generator.js
 *
 * Dedicated generator for exporting the CodeLens Engineering Health & Architectural Audit Report.
 * Synthesizes deterministic quality metrics, Mermaid topology diagrams, prioritized improvement
 * roadmaps, and file-level deep links into a standalone Markdown document.
 */

/**
 * It receives repository findings and metrics, then formats them into structured markdown
 * with executive quality scorecards, Mermaid charts, and prioritized remediation steps.
 *
 * @param {Object} params
 * @param {Object} params.model - The engineering risk model
 * @param {string} params.repoId - Current repository identifier
 * @param {number} params.score - Calculated engineering health score (0-100)
 * @param {Set<string>} [params.ignoredIds] - Set of suppressed risk IDs
 * @param {Object|string} [params.insights] - AI architecture interpretation if available
 * @param {Array} [params.adrs] - List of generated Architecture Decision Records
 * @returns {string} Fully rendered Markdown report
 */
export function generateEngineeringHealthReportMarkdown({
  model,
  repoId,
  score,
  ignoredIds = new Set(),
  insights = null,
  adrs = [],
}) {
  if (!model) return '';

  const currentScore = score != null ? score : model.score || 0;
  const currentActive = (model.risks || []).filter(r => !ignoredIds.has(r.id));
  const currentIgnored = [
    ...(model.ignoredRisks || []),
    ...(model.risks || []).filter(r => ignoredIds.has(r.id) && !(model.ignoredRisks || []).find(ir => ir.id === r.id)),
  ].filter(r => ignoredIds.has(r.id));

  const critCount = currentActive.filter(r => r.severity === 'critical').length;
  const highCount = currentActive.filter(r => r.severity === 'high').length;
  const warnCount = currentActive.filter(r => r.severity === 'warning').length;

  const deadCodeFiles = currentActive.filter(r => r.title === 'Dead / Unreachable File').map(r => r.file);
  const clonesList = currentActive
    .filter(r => r.title === 'Structural Code Clone')
    .map(r => ({
      count: r.evidence?.count || 0,
      instances: r.evidence?.instances || [],
    }));
  const hotspotList = currentActive
    .filter(r => r.title?.startsWith('Behavioral Hotspot'))
    .map(r => ({
      file: r.file,
      score: r.evidence?.hotspotScore || r.evidence?.compositeRisk || 0,
      churnScore: r.evidence?.churnScore || 0,
      complexityScore: r.evidence?.complexityScore || 0,
      quadrant: r.evidence?.quadrant || 'CRITICAL_HOTSPOT',
    }));
  const coChangeList = currentActive.filter(r => r.title === 'Hidden Logical Coupling (Temporal Co-Change)');

  const dateStr = new Date().toLocaleDateString(undefined, {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });
  const timeStr = new Date().toLocaleTimeString();

  const healthBadge =
    currentScore >= 90
      ? '🟢 EXCELLENT (90-100)'
      : currentScore >= 70
        ? '🟡 GOOD / MODERATE (70-89)'
        : currentScore >= 50
          ? '🟠 AT RISK (50-69)'
          : '🔴 CRITICAL DEBT (0-49)';

  // Category breakdown
  const categoryCounts = {};
  currentActive.forEach(r => {
    const cat = r.category || 'OTHER';
    categoryCounts[cat] = (categoryCounts[cat] || 0) + 1;
  });

  let md = `# 🏛️ CodeLens Engineering Health & Architectural Audit Report\n\n`;
  md += `> **Automated Deterministic Analysis & Architectural Risk Assessment**  \n`;
  md += `> Generated by **CodeLens Intelligence Engine** on **${dateStr} at ${timeStr}**  \n`;
  md += `> **Target Repository**: \`${repoId}\`\n\n`;
  md += `---\n\n`;

  // ── 1. Executive Quality Scorecard ──
  md += `## 1. 📊 Executive Quality Scorecard\n\n`;
  md += `| Metric | Current Value | Evaluation |\n`;
  md += `| :--- | :--- | :--- |\n`;
  md += `| **Engineering Health Score** | **${currentScore} / 100** | ${healthBadge} |\n`;
  md += `| **Total Files Analyzed** | **${model.metrics?.totalFiles || 1}** | Repository Scope |\n`;
  md += `| **Active Risk Findings** | **${currentActive.length}** | Requires Architectural Attention |\n`;
  md += `| **Suppressed / Ignored Risks** | **${currentIgnored.length}** | Maintained in Local Audit Policy |\n`;
  md += `| **🔴 Critical Severity** | **${critCount}** | ${critCount > 0 ? 'Immediate Intervention Recommended' : 'Optimal'} |\n`;
  md += `| **🟠 High Severity** | **${highCount}** | ${highCount > 0 ? 'Refactoring Priority' : 'Optimal'} |\n`;
  md += `| **🟡 Warning Severity** | **${warnCount}** | Technical Debt Observations |\n`;
  md += `| **Behavioral Hotspots** | **${hotspotList.length}** | High Churn × Complexity Intersection |\n`;
  md += `| **Structural Code Clones** | **${clonesList.length}** | Duplication Clusters |\n`;
  md += `| **Dead / Unreachable Modules** | **${deadCodeFiles.length}** | Zero Inbound Reference Files |\n`;
  md += `| **Drafted Decision Records (ADRs)** | **${adrs.length}** | Documented Governance Decisions |\n\n`;

  // ── 2. Architectural Diagrams ──
  md += `## 2. 📈 Architecture & Risk Topology Diagrams\n\n`;
  md += `### 2.1 Risk Distribution by Category\n\n`;
  md += `\`\`\`mermaid\npie title Engineering Risks by Category\n`;
  for (const [cat, count] of Object.entries(categoryCounts)) {
    md += `  "${cat}" : ${count}\n`;
  }
  if (Object.keys(categoryCounts).length === 0) {
    md += `  "No Risks Detected" : 1\n`;
  }
  md += `\`\`\`\n\n`;

  md += `### 2.2 Behavioral Hotspots & Coupling Topology\n\n`;
  md += `Visualizes defect-dense hotspots (Adam Tornhill Matrix) and temporal co-change couplings across files:\n\n`;
  md += `\`\`\`mermaid\ngraph TD\n`;
  md += `  classDef critical fill:#fee2e2,stroke:#ef4444,stroke-width:2px,color:#991b1b;\n`;
  md += `  classDef high fill:#ffedd5,stroke:#f97316,stroke-width:2px,color:#9a3412;\n`;
  md += `  classDef node fill:#f8fafc,stroke:#64748b,stroke-width:1px,color:#0f172a;\n\n`;

  const safeId = str => (str || '').replace(/[^a-zA-Z0-9_]/g, '_');
  const renderedNodes = new Set();

  hotspotList.slice(0, 8).forEach(h => {
    const nId = safeId(h.file);
    if (!renderedNodes.has(nId)) {
      renderedNodes.add(nId);
      const fName = h.file.split('/').pop();
      md += `  ${nId}["🔥 ${fName}<br/>Hotspot Score: ${h.score}/100<br/>Churn: ${h.churnScore} | Complexity: ${h.complexityScore}"]:::critical\n`;
    }
  });

  coChangeList.slice(0, 8).forEach(co => {
    const fA = co.evidence?.fileA || co.file;
    const fB = co.evidence?.fileB || co.evidence?.coupledFiles?.[0];
    if (fA && fB) {
      const idA = safeId(fA);
      const idB = safeId(fB);
      if (!renderedNodes.has(idA)) {
        renderedNodes.add(idA);
        md += `  ${idA}["${fA.split('/').pop()}"]:::high\n`;
      }
      if (!renderedNodes.has(idB)) {
        renderedNodes.add(idB);
        md += `  ${idB}["${fB.split('/').pop()}"]:::high\n`;
      }
      md += `  ${idA} -.->|"Co-Change (${co.evidence?.sharedCommits || 0} commits)"| ${idB}\n`;
    }
  });

  const cycleRisks = currentActive.filter(r => r.title?.includes('Circular') || r.category === 'DEPENDENCY');
  cycleRisks.slice(0, 4).forEach(c => {
    const cycle = c.evidence?.cyclePath || [];
    for (let i = 0; i < cycle.length; i++) {
      const cur = cycle[i];
      const next = cycle[(i + 1) % cycle.length];
      const cIdA = safeId(cur);
      const cIdB = safeId(next);
      if (!renderedNodes.has(cIdA)) {
        renderedNodes.add(cIdA);
        md += `  ${cIdA}["🔄 ${cur.split('/').pop()}"]:::critical\n`;
      }
      if (!renderedNodes.has(cIdB)) {
        renderedNodes.add(cIdB);
        md += `  ${cIdB}["🔄 ${next.split('/').pop()}"]:::critical\n`;
      }
      md += `  ${cIdA} ==>|"Cycle Loop"| ${cIdB}\n`;
    }
  });

  if (renderedNodes.size === 0) {
    md += `  CleanRepo["✅ No Critical Hotspots or Cyclic Dependencies Detected"]:::node\n`;
  }
  md += `\`\`\`\n\n`;

  // ── 3. Prioritized Improvement Roadmap ──
  md += `## 3. 🎯 Prioritized Architectural Improvement Roadmap\n\n`;
  let stepNum = 1;

  if (cycleRisks.length > 0) {
    md += `### Step ${stepNum++}: Break Circular Dependency Cycles (Critical Priority)\n`;
    md += `- **Problem**: Cyclic dependencies cause tight coupling, fragile initialization order, and hinder modular isolation.\n`;
    md += `- **Remediation**: Extract shared interfaces or utility types into a dedicated lower-tier module to invert the dependency direction.\n`;
    md += `- **Affected Files**:\n`;
    cycleRisks.forEach(cr => {
      const path = cr.evidence?.cyclePath?.join(' ➔ ') || cr.file;
      md += `  - \`${path}\` (Risk ID: \`${cr.id?.slice(5, 13) || cr.id}\`)\n`;
    });
    md += `\n`;
  }

  if (hotspotList.length > 0) {
    md += `### Step ${stepNum++}: Refactor Behavioral Hotspots (High Priority)\n`;
    md += `- **Problem**: Frequently modified files with elevated cyclomatic complexity exhibit the highest bug defect leakage (Adam Tornhill Forensic Software Analysis).\n`;
    md += `- **Remediation**: Decompose oversized functions into single-responsibility units and establish high test coverage before modifying feature logic.\n`;
    md += `- **Top Hotspots**:\n`;
    hotspotList.slice(0, 5).forEach(h => {
      md += `  - [\`${h.file}\`](file://${h.file}): Hotspot Score **${h.score}/100** (Churn: ${h.churnScore}, Complexity: ${h.complexityScore}, Quadrant: \`${h.quadrant}\`)\n`;
    });
    md += `\n`;
  }

  if (coChangeList.length > 0) {
    md += `### Step ${stepNum++}: Decouple Temporal Co-Change Modules\n`;
    md += `- **Problem**: Files that change together without direct import references indicate hidden coupling or missing architectural abstractions.\n`;
    md += `- **Remediation**: Introduce an explicit facade, event bus, or shared configuration contract.\n`;
    coChangeList.slice(0, 5).forEach(cc => {
      const fA = cc.evidence?.fileA || cc.file;
      const fB = cc.evidence?.fileB || cc.evidence?.coupledFiles?.[0];
      md += `  - \`${fA}\` & \`${fB}\` (${cc.evidence?.sharedCommits || 0} shared commits)\n`;
    });
    md += `\n`;
  }

  if (clonesList.length > 0) {
    md += `### Step ${stepNum++}: Consolidate Structural Code Clones\n`;
    md += `- **Problem**: Duplicated AST logic fragments force parallel maintenance and lead to inconsistent bug fixes.\n`;
    md += `- **Remediation**: Consolidate cloned functions into a shared module.\n`;
    clonesList.slice(0, 5).forEach(c => {
      const instances = c.instances || [];
      md += `  - Clone group with **${instances.length}** instances:\n`;
      instances.forEach(i => {
        md += `    - \`${i.filePath || '—'}\` (\`${i.name || 'block'}\`)\n`;
      });
    });
    md += `\n`;
  }

  if (deadCodeFiles.length > 0) {
    md += `### Step ${stepNum++}: Prune Dead & Unreachable Files\n`;
    md += `- **Problem**: Unused files bloat the bundle and create cognitive overhead for engineers.\n`;
    md += `- **Remediation**: Verify if these files are external entry points or dynamic imports. If unreferenced, safely remove them.\n`;
    deadCodeFiles.slice(0, 5).forEach(df => {
      md += `  - [\`${df}\`](file://${df})\n`;
    });
    md += `\n`;
  }

  // ── 4. Detailed Active Risks Inventory ──
  md += `## 4. 🔍 Detailed Active Risks Inventory & Deep Links\n\n`;
  ['critical', 'high', 'warning'].forEach(sev => {
    const risksOfSev = currentActive.filter(r => r.severity === sev);
    if (risksOfSev.length === 0) return;
    const icon = sev === 'critical' ? '🔴' : sev === 'high' ? '🟠' : '🟡';
    md += `### ${icon} ${sev.toUpperCase()} Severity Findings (${risksOfSev.length})\n\n`;

    risksOfSev.forEach(r => {
      const shortId = r.id?.slice(5, 13) || r.id;
      const lineRef = r.evidence?.location?.startLine ? `#L${r.evidence.location.startLine}` : '';
      const fileLink = r.file ? `[\`${r.file}${lineRef}\`](file://${r.file}${lineRef})` : '*(Repository-wide)*';
      const exploreLink = r.file
        ? `[Inspect in CodeLens Explore View](http://localhost:5173/explore/${encodeURIComponent(repoId)}/code?file=${encodeURIComponent(r.file)})`
        : '';

      md += `#### ${r.title}\n`;
      md += `- **Risk ID**: \`${r.id}\` (Short ID: \`${shortId}\`)\n`;
      md += `- **Category**: \`${r.category}\`\n`;
      md += `- **File**: ${fileLink} ${exploreLink ? `· ${exploreLink}` : ''}\n`;
      md += `- **Description**: ${r.description || r.message}\n`;
      if (r.evidence) {
        if (r.evidence.hotspotScore != null) {
          md += `- **Hotspot Metrics**: Hotspot Score: ${r.evidence.hotspotScore}/100, Churn: ${r.evidence.churnScore}/100, Complexity: ${r.evidence.complexityScore}/100, Quadrant: \`${r.evidence.quadrant}\`\n`;
        }
        if (r.evidence.lineCount != null && r.evidence.threshold != null) {
          md += `- **Size Metrics**: ${r.evidence.lineCount} lines (Threshold: ${r.evidence.threshold} lines, Method: ${r.evidence.detectionMethod || 'Tukey IQR'})\n`;
        }
        if (r.evidence.cyclePath) {
          md += `- **Cycle Path**: \`${r.evidence.cyclePath.join(' ➔ ')}\`\n`;
        }
        if (r.evidence.instances && r.evidence.instances.length > 0) {
          md += `- **Clone Instances** (${r.evidence.instances.length}):\n`;
          r.evidence.instances.forEach(inst => {
            const iLine = inst.location?.startLine ? `#L${inst.location.startLine}` : '';
            md += `  - \`${inst.filePath || r.file}${iLine}\` - \`${inst.name || 'clone'}\`\n`;
          });
        }
      }
      md += `\n`;
    });
  });

  // ── 5. AI Architectural Insights ──
  if (insights) {
    md += `## 5. 💡 AI Architectural Interpretation & Strategic Inferences\n\n`;
    if (typeof insights === 'string') {
      md += `${insights}\n\n`;
    } else {
      if (insights.summary) md += `### Executive Summary\n${insights.summary}\n\n`;
      if (insights.observations && Array.isArray(insights.observations)) {
        md += `### Key Architectural Inferences\n`;
        insights.observations.forEach(obs => {
          md += `- ${obs}\n`;
        });
        md += `\n`;
      }
      if (insights.recommendations && Array.isArray(insights.recommendations)) {
        md += `### AI Recommended Action Plan\n`;
        insights.recommendations.forEach(rec => {
          md += `- ${rec}\n`;
        });
        md += `\n`;
      }
    }
  }

  // ── 6. ADR Registry ──
  if (adrs.length > 0) {
    md += `## 6. 🗄️ Architectural Decision Records (ADRs) Registry\n\n`;
    md += `Recorded architectural governance decisions for repository \`${repoId}\`:\n\n`;
    adrs.forEach(adr => {
      const d = adr.data || {};
      md += `### ADR: ${d.title || adr.cacheKey}\n`;
      md += `- **Status**: \`${d.status || 'Proposed'}\` | **Date**: ${d.date || '—'}\n`;
      if (d.context) md += `- **Context**: ${d.context}\n`;
      if (d.decision) md += `- **Decision**: ${d.decision}\n`;
      if (d.consequences) md += `- **Consequences**: ${d.consequences}\n`;
      md += `\n`;
    });
  }

  // ── 7. Suppressed & Ignored Risks Audit Trail ──
  if (currentIgnored.length > 0) {
    md += `## 7. 📋 Suppressed & Ignored Risks Audit Trail\n\n`;
    md += `These risks were suppressed by engineers and excluded from active penalty score calculations:\n\n`;
    md += `| Risk ID | Title | Category | Severity | File |\n`;
    md += `| :--- | :--- | :--- | :--- | :--- |\n`;
    currentIgnored.forEach(ir => {
      md += `| \`${ir.id}\` | ${ir.title} | \`${ir.category}\` | \`${ir.severity}\` | \`${ir.file || '—'}\` |\n`;
    });
    md += `\n`;
  }

  md += `---\n*Report generated deterministically by [CodeLens](http://localhost:5173). Maintain deterministic facts before applying AI proxies.*`;
  return md;
}

/**
 * Generates the report and triggers a browser file download.
 *
 * @param {Object} params
 * @param {Object} params.model - The engineering risk model
 * @param {string} params.repoId - Current repository identifier
 * @param {number} params.score - Calculated engineering health score (0-100)
 * @param {Set<string>} [params.ignoredIds] - Set of suppressed risk IDs
 * @param {Object|string} [params.insights] - AI architecture interpretation
 * @param {Object} [params.repositoryApi] - API client to query persisted ADRs
 */
export async function downloadEngineeringHealthReport({
  model,
  repoId,
  score,
  ignoredIds = new Set(),
  insights = null,
  repositoryApi = null,
}) {
  if (!model) return;

  let adrs = [];
  if (repositoryApi?.listADRs) {
    try {
      const res = await repositoryApi.listADRs(repoId);
      adrs = res?.data || [];
    } catch {
      // non-fatal if ADR fetching fails
    }
  }

  const md = generateEngineeringHealthReportMarkdown({
    model,
    repoId,
    score,
    ignoredIds,
    insights,
    adrs,
  });

  const blob = new Blob([md], { type: 'text/markdown;charset=utf-8' });
  const safeRepo = (repoId || 'repo').replace(/[^a-zA-Z0-9-]/g, '_');
  const dateStamp = new Date().toISOString().replace(/[:.]/g, '-').split('T').join('_');
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `engineering_health_${safeRepo}_${dateStamp}.md`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
