import React, { useState, useEffect } from 'react';
import { createPortal } from 'react-dom';
import {
  X,
  Copy,
  Download,
  RefreshCw,
  AlertCircle,
  FileText,
  Loader2,
  Sparkles,
  CloudOff,
  Save,
  BookOpen,
  Check,
} from 'lucide-react';
import { repositoryApi } from '../../shared/api';
import { useToast } from '../../shared/context/ToastContext';
import ConfirmAiModal from '../../shared/components/ai/ConfirmAiModal';
import { repositoryStore } from '../../services/analyzer/repository/repository.store.js';
import { aiArtifactStore, buildCacheKey } from '../../services/storage/aiArtifact.store.js';
import { sanitizeAiError } from '../../shared/utils/aiError.js';

export default function ADRPanel({ repoId, risk, initialAdr, onClose, onOpenRegistry }) {
  const [adr, setAdr] = useState(initialAdr || null);
  const [dirty, setDirty] = useState(false);
  const [saving, setSaving] = useState(false);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState(null);
  const [showConfirmModal, setShowConfirmModal] = useState(false);
  const [showRegenerateModal, setShowRegenerateModal] = useState(false);
  const { addToast } = useToast();

  // Sync initialAdr if provided externally (e.g., from the ADR Registry)
  useEffect(() => {
    if (initialAdr) {
      setAdr(initialAdr);
      setDirty(false);
      setError(null);
    }
  }, [initialAdr]);

  // Check for an existing cached ADR when risk changes, without automatically triggering AI generation
  useEffect(() => {
    if (initialAdr) return;
    setAdr(null);
    setDirty(false);
    setError(null);
    let isMounted = true;
    async function loadCached() {
      if (!risk) return;
      try {
        const record = await repositoryStore.get(repoId).catch(() => null);
        const cacheKey = buildCacheKey(repoId, 'adr', risk.id || risk.title || '');
        const cached = await aiArtifactStore.get(cacheKey, record?.analysisVersion);
        if (cached && isMounted) {
          setAdr(prev => prev || cached);
        }
      } catch {
        // ignore cache lookup errors
      }
    }
    loadCached();
    return () => {
      isMounted = false;
    };
  }, [repoId, risk?.id, initialAdr]);

  const generate = async () => {
    setLoading(true);
    setError(null);
    try {
      const res = await repositoryApi.generateADR(repoId, risk);
      setAdr(res.data);
      setDirty(false);
      addToast({
        title: 'ADR Draft Ready',
        description: 'Architecture Decision Record drafted with AI.',
        type: 'success',
      });
    } catch (err) {
      setError(sanitizeAiError(err));
    } finally {
      setLoading(false);
    }
  };

  const handleChange = (field, value) => {
    setAdr(prev => ({ ...prev, [field]: value }));
    setDirty(true);
  };

  const handleSave = async () => {
    if (!adr) return;
    setSaving(true);
    try {
      const contextKey = risk?.id || risk?.title || adr.contextKey || adr.id || '';
      await repositoryApi.saveADR(repoId, contextKey, adr);
      setDirty(false);
      addToast({
        title: 'Changes Saved',
        description: 'ADR was updated in your repository records.',
        type: 'success',
      });
    } catch (err) {
      addToast({
        title: 'Save Failed',
        description: err.message,
        type: 'error',
      });
    } finally {
      setSaving(false);
    }
  };

  // Active ADR object (prefers local state, falls back to initialAdr immediately)
  const activeAdr = adr || initialAdr;

  const getMarkdown = () => {
    const item = activeAdr;
    if (!item) return '';
    return `# ADR: ${item.title || 'Architecture Decision Record'}
    
## Status
${item.status || 'Proposed'}

## Context
${item.context || ''}

## Decision
${item.decision || ''}

## Consequences
${item.consequences || ''}

## Alternatives
${item.alternatives || ''}

## Evidence
${item.evidence || ''}

---
*Generated by CodeLens on ${item.date || new Date().toISOString().split('T')[0]}*
`;
  };

  const handleCopy = () => {
    navigator.clipboard.writeText(getMarkdown());
    addToast({ title: 'Copied', description: 'ADR copied to clipboard', type: 'success' });
  };

  const handleDownload = () => {
    const item = activeAdr;
    if (!item) return;
    const dateStamp = (item.date || new Date().toISOString().split('T')[0]).replace(/[:.]/g, '-');
    const safeId = (item.id || 'adr').substring(0, 8);
    const blob = new Blob([getMarkdown()], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `adr-${safeId}_${dateStamp}.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  // Close on Escape key if no confirm modal is active
  useEffect(() => {
    if (!risk && !initialAdr && !adr) return;
    const handleKeyDown = e => {
      if (e.key === 'Escape' && !showConfirmModal && !showRegenerateModal) {
        onClose?.();
      }
    };
    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, [risk, initialAdr, adr, onClose, showConfirmModal, showRegenerateModal]);

  if (!risk && !initialAdr && !adr) return null;

  const content = (
    <>
      {/* Click-away backdrop */}
      <div
        className="fixed inset-0 bg-black/50 backdrop-blur-xs z-[110] transition-opacity animate-in fade-in duration-200"
        onClick={onClose}
        aria-hidden="true"
      />

      <div className="fixed inset-y-0 right-0 w-[600px] max-w-[90vw] bg-surface border-l border-border shadow-2xl z-[111] flex flex-col transform transition-transform duration-300 animate-in slide-in-from-right">
        <div className="h-12 px-4 border-b border-border flex items-center justify-between shrink-0 bg-panel">
          <div className="flex items-center gap-2.5">
            <FileText className="w-4 h-4 text-accent" />
            <h2 className="text-sm font-semibold text-text">
              {risk ? 'Draft Architecture Decision Record' : 'Architecture Decision Record'}
            </h2>
          </div>
          <div className="flex items-center gap-2">
            {onOpenRegistry && (
              <button
                onClick={onOpenRegistry}
                aria-label="View all ADRs"
                title="View All ADRs"
                className="p-1 px-2.5 text-muted hover:text-accent hover:bg-surface rounded-md border border-border/40 hover:border-accent/40 transition-colors flex items-center gap-1.5 text-xs font-medium cursor-pointer"
              >
                <BookOpen className="w-3.5 h-3.5" />
                <span>All ADRs</span>
              </button>
            )}
            <button
              onClick={onClose}
              aria-label="Close ADR panel"
              title="Close panel (Esc)"
              className="p-1.5 px-2.5 text-muted hover:text-text hover:bg-surface rounded-md border border-border/40 hover:border-border transition-colors flex items-center gap-1.5 text-xs font-medium cursor-pointer"
            >
              <X className="w-4 h-4" />
              <span>Close</span>
            </button>
          </div>
        </div>

        <div className="flex-1 overflow-y-auto p-6 custom-scrollbar bg-surface/50">
          {loading ? (
            <div className="h-full flex flex-col items-center justify-center text-muted">
              <Loader2 className="w-8 h-8 animate-spin mb-4 text-accent" />
              <p className="text-sm font-medium text-text">Generating ADR context with AI...</p>
              <p className="text-xs text-muted mt-1">Analyzing finding, consequences, and alternatives</p>
            </div>
          ) : error ? (
            error.type === 'offline' ? (
              <div className="flex flex-col items-center justify-center p-8 bg-panel border border-border rounded-xl text-center">
                <div className="w-12 h-12 rounded-full bg-surface border border-border flex items-center justify-center text-muted mb-3 shadow-inner">
                  <CloudOff className="w-6 h-6 text-muted" />
                </div>
                <span className="font-semibold text-text text-base mb-1">AI Offline</span>
                <span className="text-[11px] font-semibold text-muted uppercase tracking-wider mb-3">
                  No AI Provider Configured
                </span>
                <p className="text-xs text-muted max-w-sm mb-5 leading-relaxed">
                  No active AI provider was found. Your deterministic AST analysis, dependency graphs, and health
                  metrics remain fully available offline.
                </p>
                <div className="p-3.5 bg-surface border border-border/80 rounded-lg text-left text-xs text-muted max-w-sm w-full mb-5">
                  <span className="font-medium text-text block mb-1">To enable AI drafting:</span>
                  Configure an AI provider key (such as Groq or Google Gemini) in your server environment settings.
                </div>
                <button
                  onClick={() => setError(null)}
                  className="px-4 py-2 bg-surface hover:bg-surface/80 border border-border rounded-md text-xs font-medium text-text transition-colors cursor-pointer"
                >
                  Back to Overview
                </button>
              </div>
            ) : (
              <div className="flex flex-col items-center justify-center p-6 bg-warning/10 border border-warning/30 rounded-xl text-center">
                <AlertCircle className="w-8 h-8 mb-2 text-warning" />
                <span className="font-semibold text-text mb-1">
                  {error.title || 'AI Service Temporarily Unavailable'}
                </span>
                <p className="text-xs text-muted max-w-sm mb-5 leading-relaxed">{error.message}</p>
                <div className="flex items-center gap-3">
                  <button
                    onClick={() => setError(null)}
                    className="px-3.5 py-1.5 bg-surface border border-border hover:bg-surface/80 rounded-md text-xs text-muted hover:text-text transition-colors cursor-pointer"
                  >
                    Cancel
                  </button>
                  <button
                    onClick={() => {
                      setError(null);
                      setShowConfirmModal(true);
                    }}
                    className="px-4 py-1.5 bg-accent hover:bg-accent-hover text-white rounded-md text-xs font-medium transition-colors flex items-center gap-2 cursor-pointer shadow-sm"
                  >
                    <RefreshCw className="w-3.5 h-3.5" /> Retry with Confirmation
                  </button>
                </div>
              </div>
            )
          ) : activeAdr ? (
            <div className="flex flex-col gap-5">
              <div>
                <label className="block text-xs font-medium text-muted uppercase tracking-wider mb-1">Title</label>
                <input
                  value={activeAdr.title || ''}
                  onChange={e => handleChange('title', e.target.value)}
                  className="w-full bg-panel border border-border rounded-md px-3 py-2 text-sm text-text focus:outline-none focus:border-accent"
                />
              </div>

              <div>
                <label className="block text-xs font-medium text-muted uppercase tracking-wider mb-1">Status</label>
                <select
                  value={activeAdr.status || 'Proposed'}
                  onChange={e => handleChange('status', e.target.value)}
                  className="w-full bg-panel border border-border rounded-md px-3 py-2 text-sm text-text focus:outline-none focus:border-accent"
                >
                  <option value="Proposed">Proposed</option>
                  <option value="Accepted">Accepted</option>
                  <option value="Rejected">Rejected</option>
                  <option value="Deprecated">Deprecated</option>
                  <option value="Superseded">Superseded</option>
                </select>
              </div>

              <div>
                <label className="block text-xs font-medium text-muted uppercase tracking-wider mb-1">Context</label>
                <textarea
                  value={activeAdr.context || ''}
                  onChange={e => handleChange('context', e.target.value)}
                  rows={4}
                  className="w-full bg-panel border border-border rounded-md px-3 py-2 text-sm text-text focus:outline-none focus:border-accent custom-scrollbar"
                />
              </div>

              <div>
                <label className="block text-xs font-medium text-muted uppercase tracking-wider mb-1">Decision</label>
                <textarea
                  value={activeAdr.decision || ''}
                  onChange={e => handleChange('decision', e.target.value)}
                  rows={3}
                  className="w-full bg-panel border border-border rounded-md px-3 py-2 text-sm text-text focus:outline-none focus:border-accent custom-scrollbar"
                />
              </div>

              <div>
                <label className="block text-xs font-medium text-muted uppercase tracking-wider mb-1">
                  Consequences
                </label>
                <textarea
                  value={activeAdr.consequences || ''}
                  onChange={e => handleChange('consequences', e.target.value)}
                  rows={4}
                  className="w-full bg-panel border border-border rounded-md px-3 py-2 text-sm text-text focus:outline-none focus:border-accent custom-scrollbar"
                />
              </div>

              <div>
                <label className="block text-xs font-medium text-muted uppercase tracking-wider mb-1">
                  Alternatives
                </label>
                <textarea
                  value={activeAdr.alternatives || ''}
                  onChange={e => handleChange('alternatives', e.target.value)}
                  rows={3}
                  className="w-full bg-panel border border-border rounded-md px-3 py-2 text-sm text-text focus:outline-none focus:border-accent custom-scrollbar"
                />
              </div>

              <div>
                <label className="block text-xs font-medium text-muted uppercase tracking-wider mb-1">Evidence</label>
                <textarea
                  value={activeAdr.evidence || ''}
                  onChange={e => handleChange('evidence', e.target.value)}
                  rows={2}
                  className="w-full bg-panel border border-border rounded-md px-3 py-2 text-sm focus:outline-none focus:border-accent custom-scrollbar text-muted"
                />
              </div>
            </div>
          ) : risk ? (
            /* Pre-generation confirmation & overview view — protects from token waste */
            <div className="flex flex-col h-full items-center justify-center p-6 text-center">
              <div className="w-14 h-14 rounded-2xl bg-accent/15 border border-accent/30 flex items-center justify-center mb-5 text-accent shadow-inner">
                <FileText className="w-7 h-7" />
              </div>
              <h3 className="text-base font-semibold text-text mb-2">Draft Architecture Decision Record</h3>
              <p className="text-xs text-muted max-w-sm mb-6 leading-relaxed">
                Synthesize this architectural finding into a structured markdown ADR (Status, Context, Decision,
                Consequences, and Alternatives) using AI.
              </p>

              {/* Finding Context Card */}
              <div className="w-full max-w-md p-4 rounded-xl bg-panel border border-border text-left mb-6 flex flex-col gap-2">
                <div className="flex items-center justify-between gap-2">
                  <span className="text-xs font-semibold text-text truncate max-w-[260px]">{risk.title}</span>
                  <span className="text-[10px] uppercase font-bold tracking-wider px-2 py-0.5 rounded bg-accent/15 text-accent border border-accent/30 shrink-0">
                    {risk.severity}
                  </span>
                </div>
                {risk.file && <div className="text-[11px] font-mono text-muted truncate">{risk.file}</div>}
                <p className="text-xs text-muted/80 line-clamp-2 mt-1">
                  {typeof risk.description === 'string'
                    ? risk.description
                    : typeof risk.message === 'string'
                      ? risk.message
                      : ''}
                </p>
              </div>

              <button
                onClick={() => setShowConfirmModal(true)}
                className="px-5 py-2.5 bg-accent hover:bg-accent-hover text-white rounded-xl text-sm font-medium transition-all shadow-lg shadow-accent/20 flex items-center gap-2 group cursor-pointer"
              >
                <Sparkles className="w-4 h-4 transition-transform group-hover:scale-110" />
                Draft ADR with AI
              </button>
              <span className="text-[11px] text-muted/70 mt-2.5 flex items-center gap-1">
                ⚡ Requires confirmation · Consumes ~800 tokens
              </span>
            </div>
          ) : (
            <div className="flex flex-col h-full items-center justify-center p-6 text-center text-muted">
              <FileText className="w-10 h-10 mb-3 opacity-40 text-muted" />
              <p className="text-sm font-medium text-text mb-1">No Decision Record Selected</p>
              <p className="text-xs text-muted max-w-xs">
                Select an ADR from the registry or draft one from a finding.
              </p>
            </div>
          )}
        </div>

        <div className="px-6 py-4 border-t border-border flex items-center justify-between shrink-0 bg-panel">
          <div className="flex items-center gap-2">
            {risk && (
              <button
                onClick={() => setShowRegenerateModal(true)}
                disabled={loading || !activeAdr}
                className="px-3 py-1.5 text-xs font-medium text-muted hover:text-text flex items-center gap-2 transition-colors disabled:opacity-50 cursor-pointer"
              >
                <RefreshCw className="w-3.5 h-3.5" /> Regenerate
              </button>
            )}
            {activeAdr && (
              <button
                onClick={handleSave}
                disabled={saving || !dirty}
                className={`px-3 py-1.5 text-xs font-medium rounded border transition-colors flex items-center gap-1.5 cursor-pointer ${
                  dirty
                    ? 'bg-accent/20 border-accent/40 text-accent hover:bg-accent/30'
                    : 'bg-surface border-border/60 text-muted/80 opacity-70'
                }`}
                title={dirty ? 'Save edits to IndexedDB' : 'All changes saved'}
              >
                {saving ? (
                  <Loader2 className="w-3.5 h-3.5 animate-spin" />
                ) : dirty ? (
                  <Save className="w-3.5 h-3.5" />
                ) : (
                  <Check className="w-3.5 h-3.5 text-green-400" />
                )}
                <span>{saving ? 'Saving...' : dirty ? 'Save Changes' : 'Saved'}</span>
              </button>
            )}
          </div>

          <div className="flex items-center gap-3">
            <button
              onClick={onClose}
              className="px-4 py-2 bg-surface border border-border hover:bg-surface/80 text-muted hover:text-text rounded-md text-sm font-medium transition-colors cursor-pointer"
            >
              Close
            </button>
            <button
              onClick={handleCopy}
              disabled={loading || !activeAdr}
              className="px-4 py-2 bg-surface border border-border hover:bg-surface/80 rounded-md text-sm font-medium transition-colors disabled:opacity-50 flex items-center gap-2 cursor-pointer"
            >
              <Copy className="w-4 h-4" /> Copy Markdown
            </button>
            <button
              onClick={handleDownload}
              disabled={loading || !activeAdr}
              className="px-4 py-2 bg-accent hover:bg-accent-hover text-white rounded-md text-sm font-medium transition-colors disabled:opacity-50 flex items-center gap-2 cursor-pointer"
            >
              <Download className="w-4 h-4" /> Download .md
            </button>
          </div>
        </div>
      </div>

      {/* Confirmation Modal for initial generation */}
      {risk && (
        <ConfirmAiModal
          isOpen={showConfirmModal}
          onClose={() => setShowConfirmModal(false)}
          onConfirm={() => {
            setShowConfirmModal(false);
            generate();
          }}
          title="Draft Architecture Decision Record"
          subtitle={`Finding: ${risk.title}`}
          description="CodeLens will synthesize this finding's structural evidence, consequences, and alternative remediation paths into an industry-standard ADR document."
          findingContext={risk}
          tokenEstimate="~800 tokens"
          confirmText="Proceed to AI"
        />
      )}

      {/* Confirmation Modal for regeneration */}
      {risk && (
        <ConfirmAiModal
          isOpen={showRegenerateModal}
          onClose={() => setShowRegenerateModal(false)}
          onConfirm={() => {
            setShowRegenerateModal(false);
            generate();
          }}
          title="Regenerate Architecture Decision Record"
          subtitle="Overwrite Existing Draft"
          description="This will re-run the AI synthesis for this finding and overwrite your current ADR draft with fresh recommendations."
          findingContext={risk}
          tokenEstimate="~800 tokens"
          confirmText="Proceed to AI"
        />
      )}
    </>
  );

  return typeof document !== 'undefined' ? createPortal(content, document.body) : content;
}
