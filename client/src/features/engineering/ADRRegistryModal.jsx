import React, { useState, useEffect, useMemo, useCallback } from 'react';
import { createPortal } from 'react-dom';
import {
  X,
  Search,
  FileText,
  Copy,
  Download,
  Trash2,
  Calendar,
  Sparkles,
  ExternalLink,
  Filter,
  CheckCircle2,
  Clock,
  AlertCircle,
  Archive,
  BookOpen,
} from 'lucide-react';
import { repositoryApi } from '../../shared/api';
import { useToast } from '../../shared/context/ToastContext';

const STATUS_CONFIG = {
  Proposed: {
    bg: 'bg-blue-500/15',
    text: 'text-blue-400',
    border: 'border-blue-500/30',
    icon: Clock,
  },
  Accepted: {
    bg: 'bg-green-500/15',
    text: 'text-green-400',
    border: 'border-green-500/30',
    icon: CheckCircle2,
  },
  Rejected: {
    bg: 'bg-red-500/15',
    text: 'text-red-400',
    border: 'border-red-500/30',
    icon: AlertCircle,
  },
  Deprecated: {
    bg: 'bg-amber-500/15',
    text: 'text-amber-400',
    border: 'border-amber-500/30',
    icon: Archive,
  },
  Superseded: {
    bg: 'bg-purple-500/15',
    text: 'text-purple-400',
    border: 'border-purple-500/30',
    icon: Archive,
  },
};

export default function ADRRegistryModal({ isOpen, onClose, repoId, onSelectAdr }) {
  const [adrs, setAdrs] = useState([]);
  const [loading, setLoading] = useState(true);
  const [searchQuery, setSearchQuery] = useState('');
  const [statusFilter, setStatusFilter] = useState('ALL');
  const [sortBy, setSortBy] = useState('newest');
  const [deletingKey, setDeletingKey] = useState(null);
  const { addToast } = useToast();

  const loadAdrs = useCallback(async () => {
    if (!repoId) return;
    setLoading(true);
    try {
      const res = await repositoryApi.listADRs(repoId);
      setAdrs(res.data || []);
    } catch (err) {
      console.warn('[ADRRegistry] Failed to load ADRs:', err);
    } finally {
      setLoading(false);
    }
  }, [repoId]);

  useEffect(() => {
    if (isOpen) {
      loadAdrs();
    }
  }, [isOpen, loadAdrs]);

  // Close on Escape key
  useEffect(() => {
    if (!isOpen) return;
    const handleKeyDown = e => {
      if (e.key === 'Escape') onClose();
    };
    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, [isOpen, onClose]);

  // Status counts for filter chips
  const statusCounts = useMemo(() => {
    const counts = { ALL: adrs.length, Proposed: 0, Accepted: 0, Rejected: 0, Deprecated: 0, Superseded: 0 };
    for (const item of adrs) {
      const st = item.data?.status || 'Proposed';
      if (counts[st] !== undefined) counts[st]++;
      else counts.Proposed++;
    }
    return counts;
  }, [adrs]);

  // Filtered & sorted ADRs
  const filteredAdrs = useMemo(() => {
    let result = [...adrs];

    // Status filter
    if (statusFilter !== 'ALL') {
      result = result.filter(item => {
        const st = item.data?.status || 'Proposed';
        return st.toLowerCase() === statusFilter.toLowerCase();
      });
    }

    // Search query across title, decision, context, consequences, evidence
    if (searchQuery.trim()) {
      const q = searchQuery.toLowerCase().trim();
      result = result.filter(item => {
        const d = item.data || {};
        return (
          (d.title && d.title.toLowerCase().includes(q)) ||
          (d.decision && d.decision.toLowerCase().includes(q)) ||
          (d.context && d.context.toLowerCase().includes(q)) ||
          (d.consequences && d.consequences.toLowerCase().includes(q)) ||
          (d.alternatives && d.alternatives.toLowerCase().includes(q)) ||
          (d.evidence && d.evidence.toLowerCase().includes(q)) ||
          (d.status && d.status.toLowerCase().includes(q))
        );
      });
    }

    // Sorting
    result.sort((a, b) => {
      if (sortBy === 'newest') return (b.cachedAt || 0) - (a.cachedAt || 0);
      if (sortBy === 'oldest') return (a.cachedAt || 0) - (b.cachedAt || 0);
      if (sortBy === 'title') {
        const titleA = (a.data?.title || '').toLowerCase();
        const titleB = (b.data?.title || '').toLowerCase();
        return titleA.localeCompare(titleB);
      }
      if (sortBy === 'status') {
        const stA = a.data?.status || '';
        const stB = b.data?.status || '';
        return stA.localeCompare(stB);
      }
      return 0;
    });

    return result;
  }, [adrs, statusFilter, searchQuery, sortBy]);

  const formatMarkdown = adr => {
    if (!adr) return '';
    return `# ADR: ${adr.title || 'Untitled Decision'}

## Status
${adr.status || 'Proposed'}

## Context
${adr.context || 'N/A'}

## Decision
${adr.decision || 'N/A'}

## Consequences
${adr.consequences || 'N/A'}

## Alternatives
${adr.alternatives || 'N/A'}

## Evidence
${adr.evidence || 'N/A'}

---
*Generated by CodeLens on ${adr.date || new Date().toISOString().split('T')[0]}*
`;
  };

  const handleCopy = (e, adr) => {
    e.stopPropagation();
    navigator.clipboard.writeText(formatMarkdown(adr));
    addToast({
      title: 'Copied to Clipboard',
      description: `"${adr.title || 'ADR'}" markdown copied.`,
      type: 'success',
    });
  };

  const handleDownload = (e, adr) => {
    e.stopPropagation();
    const dateStamp = (adr.date || new Date().toISOString().split('T')[0]).replace(/[:.]/g, '-');
    const safeTitle = (adr.title || 'adr')
      .replace(/[^a-z0-9_-]/gi, '_')
      .toLowerCase()
      .slice(0, 30);
    const blob = new Blob([formatMarkdown(adr)], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `adr-${safeTitle}_${dateStamp}.md`;
    a.click();
    URL.revokeObjectURL(url);
    addToast({
      title: 'Downloaded',
      description: `Saved adr-${safeTitle}_${dateStamp}.md`,
      type: 'success',
    });
  };

  const handleDelete = async (e, cacheKey, title) => {
    e.stopPropagation();
    try {
      await repositoryApi.deleteADR(cacheKey);
      setAdrs(prev => prev.filter(item => item.cacheKey !== cacheKey));
      setDeletingKey(null);
      addToast({
        title: 'ADR Deleted',
        description: `"${title || 'Decision record'}" was removed.`,
        type: 'success',
      });
    } catch (err) {
      addToast({
        title: 'Delete Failed',
        description: err.message,
        type: 'error',
      });
    }
  };

  if (!isOpen) return null;

  const content = (
    <>
      {/* Backdrop */}
      <div
        className="fixed inset-0 bg-black/60 backdrop-blur-xs z-[110] transition-opacity animate-in fade-in duration-200"
        onClick={onClose}
        aria-hidden="true"
      />

      {/* Drawer Panel */}
      <div className="fixed inset-y-0 right-0 w-[720px] max-w-[95vw] bg-surface border-l border-border shadow-2xl z-[111] flex flex-col transform transition-transform duration-300 animate-in slide-in-from-right">
        {/* Header */}
        <div className="h-16 px-6 border-b border-border flex items-center justify-between shrink-0 bg-panel">
          <div className="flex items-center gap-3">
            <div className="w-9 h-9 rounded-xl bg-accent/15 border border-accent/30 flex items-center justify-center text-accent">
              <BookOpen className="w-5 h-5" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h2 className="text-sm font-semibold text-text">Architecture Decision Records</h2>
                <span className="text-[11px] font-medium px-2 py-0.5 rounded-full bg-accent/15 text-accent border border-accent/25">
                  {adrs.length}
                </span>
              </div>
              <p className="text-xs text-muted">Browse, search, and manage drafted architectural decisions</p>
            </div>
          </div>

          <button
            onClick={onClose}
            aria-label="Close ADR registry"
            className="p-1.5 px-2.5 text-muted hover:text-text hover:bg-surface rounded-md border border-border/40 hover:border-border transition-colors flex items-center gap-1.5 text-xs font-medium cursor-pointer"
          >
            <X className="w-4 h-4" />
            <span>Close (Esc)</span>
          </button>
        </div>

        {/* Search & Filter Bar */}
        <div className="p-4 border-b border-border bg-surface/70 flex flex-col gap-3 shrink-0">
          {/* Search Box */}
          <div className="relative flex items-center w-full">
            <Search className="w-4 h-4 text-muted absolute left-3 pointer-events-none" />
            <input
              type="text"
              value={searchQuery}
              onChange={e => setSearchQuery(e.target.value)}
              placeholder="Search ADRs by title, decision, consequence, or status..."
              className="w-full bg-panel border border-border rounded-lg pl-9 pr-9 py-2 text-xs text-text placeholder-muted/60 focus:outline-none focus:border-accent transition-colors shadow-inner"
            />
            {searchQuery && (
              <button
                onClick={() => setSearchQuery('')}
                className="absolute right-3 p-0.5 text-muted hover:text-text cursor-pointer"
                aria-label="Clear search query"
              >
                <X className="w-3.5 h-3.5" />
              </button>
            )}
          </div>

          {/* Filter Chips & Sort Select */}
          <div className="flex items-center justify-between gap-2 flex-wrap">
            <div className="flex items-center gap-1.5 flex-wrap">
              {['ALL', 'Proposed', 'Accepted', 'Rejected', 'Deprecated'].map(status => {
                const count = statusCounts[status] || 0;
                const isActive = statusFilter === status;
                return (
                  <button
                    key={status}
                    onClick={() => setStatusFilter(status)}
                    className={`px-2.5 py-1 rounded-md text-xs font-medium transition-colors flex items-center gap-1.5 cursor-pointer ${
                      isActive
                        ? 'bg-accent text-white shadow-xs'
                        : 'bg-panel border border-border text-muted hover:text-text hover:bg-surface'
                    }`}
                  >
                    <span>{status}</span>
                    <span
                      className={`text-[10px] px-1.5 py-0.2 rounded-full ${
                        isActive ? 'bg-white/20 text-white' : 'bg-surface text-muted'
                      }`}
                    >
                      {count}
                    </span>
                  </button>
                );
              })}
            </div>

            <div className="flex items-center gap-2 shrink-0">
              <span className="text-[11px] text-muted flex items-center gap-1">
                <Filter className="w-3 h-3" /> Sort:
              </span>
              <select
                value={sortBy}
                onChange={e => setSortBy(e.target.value)}
                className="bg-panel border border-border rounded-md px-2 py-1 text-xs text-text focus:outline-none focus:border-accent cursor-pointer"
              >
                <option value="newest">Newest First</option>
                <option value="oldest">Oldest First</option>
                <option value="title">Title (A-Z)</option>
                <option value="status">By Status</option>
              </select>
            </div>
          </div>
        </div>

        {/* Content List */}
        <div className="flex-1 overflow-y-auto p-4 custom-scrollbar bg-surface/40 flex flex-col gap-3">
          {loading ? (
            <div className="h-64 flex flex-col items-center justify-center text-muted">
              <div className="w-6 h-6 border-2 border-accent border-t-transparent rounded-full animate-spin mb-3" />
              <p className="text-xs">Loading Architecture Decision Records...</p>
            </div>
          ) : filteredAdrs.length === 0 ? (
            <div className="h-72 flex flex-col items-center justify-center text-center p-6 bg-panel/50 border border-border/70 rounded-xl">
              <div className="w-12 h-12 rounded-2xl bg-surface border border-border flex items-center justify-center text-muted mb-3 shadow-inner">
                <FileText className="w-6 h-6 text-muted" />
              </div>
              <h3 className="text-sm font-semibold text-text mb-1">
                {adrs.length === 0 ? 'No ADRs Drafted Yet' : 'No Matching Decision Records'}
              </h3>
              <p className="text-xs text-muted max-w-sm mb-4 leading-relaxed">
                {adrs.length === 0
                  ? "Generate Architecture Decision Records by clicking 'Draft ADR' on any engineering risk on the Health page."
                  : `No records match "${searchQuery}" with the current filters. Try adjusting your query.`}
              </p>
              {searchQuery && (
                <button
                  onClick={() => {
                    setSearchQuery('');
                    setStatusFilter('ALL');
                  }}
                  className="px-3 py-1.5 bg-surface border border-border hover:bg-surface/80 rounded-md text-xs text-text transition-colors cursor-pointer"
                >
                  Clear Filters
                </button>
              )}
            </div>
          ) : (
            filteredAdrs.map(item => {
              const adr = item.data || {};
              const status = adr.status || 'Proposed';
              const config = STATUS_CONFIG[status] || STATUS_CONFIG.Proposed;
              const StatusIcon = config.icon;
              const dateStr = adr.date || (item.cachedAt ? new Date(item.cachedAt).toISOString().split('T')[0] : 'N/A');

              return (
                <div
                  key={item.cacheKey}
                  onClick={() => onSelectAdr?.(adr, item.cacheKey)}
                  className="group relative p-4 rounded-xl bg-panel border border-border/80 hover:border-accent/50 hover:bg-panel/90 transition-all cursor-pointer shadow-xs flex flex-col gap-2.5"
                >
                  {/* Top row: Status, Title, Date */}
                  <div className="flex items-start justify-between gap-3">
                    <div className="flex-1 min-w-0">
                      <div className="flex items-center gap-2 mb-1">
                        <span
                          className={`text-[10px] uppercase font-bold tracking-wider px-2 py-0.5 rounded-full border flex items-center gap-1 ${config.bg} ${config.text} ${config.border}`}
                        >
                          <StatusIcon className="w-3 h-3" />
                          {status}
                        </span>
                        <span className="text-[11px] font-mono text-muted flex items-center gap-1">
                          <Calendar className="w-3 h-3" />
                          {dateStr}
                        </span>
                      </div>
                      <h4 className="text-sm font-semibold text-text group-hover:text-accent transition-colors truncate">
                        {adr.title || 'Untitled Decision Record'}
                      </h4>
                    </div>

                    {/* Quick Action Buttons */}
                    <div className="flex items-center gap-1.5 opacity-90 group-hover:opacity-100 transition-opacity shrink-0">
                      <button
                        onClick={e => handleCopy(e, adr)}
                        title="Copy Markdown"
                        className="p-1.5 text-muted hover:text-text hover:bg-surface rounded-md border border-border/40 hover:border-border transition-colors cursor-pointer"
                      >
                        <Copy className="w-3.5 h-3.5" />
                      </button>
                      <button
                        onClick={e => handleDownload(e, adr)}
                        title="Download Markdown (.md)"
                        className="p-1.5 text-muted hover:text-text hover:bg-surface rounded-md border border-border/40 hover:border-border transition-colors cursor-pointer"
                      >
                        <Download className="w-3.5 h-3.5" />
                      </button>
                      <button
                        onClick={e => {
                          e.stopPropagation();
                          if (deletingKey === item.cacheKey) {
                            handleDelete(e, item.cacheKey, adr.title);
                          } else {
                            setDeletingKey(item.cacheKey);
                          }
                        }}
                        title={deletingKey === item.cacheKey ? 'Click again to confirm delete' : 'Delete ADR'}
                        className={`p-1.5 rounded-md border transition-colors cursor-pointer ${
                          deletingKey === item.cacheKey
                            ? 'bg-red-500/20 text-red-400 border-red-500/40 animate-pulse'
                            : 'text-muted hover:text-red-400 hover:bg-red-500/10 border-border/40 hover:border-red-500/30'
                        }`}
                      >
                        <Trash2 className="w-3.5 h-3.5" />
                      </button>
                    </div>
                  </div>

                  {/* Decision Snippet */}
                  {adr.decision && (
                    <div className="p-2.5 rounded-lg bg-surface/70 border border-border/60 text-xs">
                      <span className="font-semibold text-text/90 block mb-0.5 text-[11px] uppercase tracking-wider text-muted">
                        Decision:
                      </span>
                      <p className="text-muted/90 line-clamp-2 leading-relaxed">{adr.decision}</p>
                    </div>
                  )}

                  {/* Context snippet if decision absent */}
                  {!adr.decision && adr.context && (
                    <p className="text-xs text-muted line-clamp-2 leading-relaxed">{adr.context}</p>
                  )}

                  {/* Footer metadata */}
                  <div className="flex items-center justify-between text-[11px] text-muted/70 pt-1 border-t border-border/30">
                    <span className="flex items-center gap-1 font-mono text-[10px]">
                      {item.cacheKey ? item.cacheKey.split('::')[2] || '' : ''}
                    </span>
                    <span className="flex items-center gap-1 text-accent font-medium group-hover:translate-x-0.5 transition-transform">
                      Open in Editor <ExternalLink className="w-3 h-3" />
                    </span>
                  </div>
                </div>
              );
            })
          )}
        </div>

        {/* Footer */}
        <div className="h-14 px-6 border-t border-border flex items-center justify-between shrink-0 bg-panel text-xs text-muted">
          <span>
            Showing <strong className="text-text">{filteredAdrs.length}</strong> of{' '}
            <strong className="text-text">{adrs.length}</strong> decision records
          </span>
          <button
            onClick={onClose}
            className="px-4 py-1.5 bg-surface border border-border hover:bg-surface/80 text-text rounded-md text-xs font-medium transition-colors cursor-pointer"
          >
            Done
          </button>
        </div>
      </div>
    </>
  );

  return typeof document !== 'undefined' ? createPortal(content, document.body) : content;
}
